# -*- coding: utf-8 -*-
import os
import asyncio
from playwright.async_api import async_playwright

def load_env_file(env_path='.env'):
    if os.path.exists(env_path):
        with open(env_path, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith('#') and '=' in line:
                    k, v = line.split('=', 1)
                    os.environ.setdefault(k.strip(), v.strip())

load_env_file()

SITE_URL = "http://192.168.8.11:6888"
ERPNEXT_USER = os.getenv('ERPNEXT_USER', 'Administrator')
ERPNEXT_PASS = os.getenv('ERPNEXT_PASSWORD', '')

async def run():
    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True)
        context = await browser.new_context(viewport={"width": 1400, "height": 900})
        page = await context.new_page()

        await page.goto(f"{SITE_URL}/login", wait_until="networkidle", timeout=30000)
        await page.fill("#login_email", ERPNEXT_USER)
        await page.fill("#login_password", ERPNEXT_PASS)
        await page.click(".btn-login")
        await page.wait_for_load_state("networkidle", timeout=30000)
        await asyncio.sleep(4)

        info = await page.evaluate("""() => {
            return {
                sidebar_keys: Object.keys(frappe.boot?.workspace_sidebar_item || {}),
                current_sidebar_title: frappe.app?.sidebar?.sidebar_title,
                sidebar_data: frappe.app?.sidebar?.sidebar_data
            };
        }""")

        print("Sidebar keys:", info['sidebar_keys'])
        print("Current sidebar title:", info['current_sidebar_title'])
        print("Sidebar data exists:", bool(info['sidebar_data']))

        await browser.close()

asyncio.run(run())
